// ─── Activity log for downloads (meaningful events only: sets, not sheets) ──

export async function logPlanDownload(projectId: string, detail: { kind: string; count: number; label?: string }): Promise<Result> {
  try {
    const { supabase, user, profile } = await requireUser()
    // Single-sheet downloads are routine, not activity-worthy noise.
    if (detail.count < 2) return { success: true }
    await supabase.from('plan_activity').insert({
      company_id: profile.company_id, project_id: projectId, actor_id: user.id,
      action: 'downloaded', detail,
    })
    return { success: true }
  } catch (err) {
    return fail(err, 'logPlanDownload')
  }
}

